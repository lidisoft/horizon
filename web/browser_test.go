// testFS holds web/test: the runner and the *.test.js files. It is read from
// disk, so it never ships in the binary.
var testFS = os.DirFS("test")

// testPage serves the runner page, the test modules and the real app assets.
func testPage() (http.Handler, error) {
	w, err := server.NewWeb(web.FS())
	if err != nil {
		return nil, err
	}
	app := server.NewEngine(server.Deps{Log: zerolog.Nop(), Web: w})

	imports := w.Imports()
	var testFiles []string
	err = fs.WalkDir(testFS, ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(p, ".js") {
			return err
		}
		imports["horizon-test/"+p] = "/test/" + p
		if strings.HasSuffix(p, ".test.js") {
			testFiles = append(testFiles, p)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	sort.Strings(testFiles)

	var entry strings.Builder
	entry.WriteString("// Generated by web/browser_test.go: every *.test.js, then run().\n")
	for _, f := range testFiles {
		fmt.Fprintf(&entry, "import %q;\n", "horizon-test/"+f)
	}
	entry.WriteString(`import { run } from "horizon-test/runner.js";` + "\nrun();\n")

	importMap, err := json.Marshal(map[string]any{"imports": imports})
	if err != nil {
		return nil, err
	}
	tpl, err := template.ParseFS(testFS, "index.html")
	if err != nil {
		return nil, err
	}
	var page bytes.Buffer
	err = tpl.Execute(&page, map[string]any{"ImportMap": template.HTML(importMap), "LDS": w.LDSBase()})
	if err != nil {
		return nil, err
	}

	files := http.StripPrefix("/test/", http.FileServer(http.FS(testFS)))
	mux := http.NewServeMux()
	mux.HandleFunc("GET /test/{$}", func(rw http.ResponseWriter, _ *http.Request) {
		rw.Header().Set("Content-Security-Policy", server.CSP(importMap))
		rw.Header().Set("Content-Type", "text/html; charset=utf-8")
		_, _ = rw.Write(page.Bytes())
	})
	mux.HandleFunc("GET /test/entry.js", func(rw http.ResponseWriter, _ *http.Request) {
		rw.Header().Set("Content-Type", "text/javascript; charset=utf-8")
		_, _ = rw.Write([]byte(entry.String()))
	})
	// The document vectors shared with internal/document's Go tests.
	corpus := http.StripPrefix("/test/corpus/", http.FileServer(http.Dir("../internal/document/testdata")))
	mux.Handle("GET /test/corpus/", corpus)
	mux.Handle("GET /test/", http.HandlerFunc(func(rw http.ResponseWriter, r *http.Request) {
		rw.Header().Set("Cache-Control", "no-store")
		files.ServeHTTP(rw, r)
	}))
	mux.Handle("/", app)
	return mux, nil
}

// console collects the page's console and browser log messages.
type console struct {
	mu       sync.Mutex
	messages []chromedp.ConsoleMessage
}

func watchConsole(ctx context.Context) *console {
	c := &console{}
	messages := chromedp.Console(ctx)
	go func() {
		for m, err := range messages {
			if err != nil {
				return
			}
			c.mu.Lock()
			c.messages = append(c.messages, m)
			c.mu.Unlock()
		}
	}()
	return c
}

// knownIssues are browser messages accepted until an upstream fix lands.
var knownIssues = []struct{ text, why string }{}

// expectedStatus matches the browser's own log line for a 4xx answer, such
// as the 401 of GET /me while signed out: the API reports expected failures
// with status codes, and the tests assert on what the page shows instead.
var expectedStatus = regexp.MustCompile(`^Failed to load resource: the server responded with a status of 4\d\d `)

// failOnErrors fails the test for uncaught exceptions, console errors
// (except 4xx responses) and CSP violations.
func (c *console) failOnErrors(t *testing.T) {
	t.Helper()
	c.mu.Lock()
	defer c.mu.Unlock()
next:
	for _, m := range c.messages {
		if !m.IsException() && m.Type != "error" && m.Type != "assert" {
			continue
		}
		if expectedStatus.MatchString(m.Text) {
			continue
		}
		for _, k := range knownIssues {
			if strings.Contains(m.Text, k.text) {
				t.Logf("known issue (%s): %s", k.why, m.Text)
				continue next
			}
		}
		t.Errorf("browser %s", m)
	}
}

type jsResult struct {
	Name  string `json:"name"`
	OK    bool   `json:"ok"`
	Ms    int    `json:"ms"`
	Error string `json:"error"`
}

// TestWebUnits runs web/test/**/*.test.js in Chrome; each JS test is a subtest.
func TestWebUnits(t *testing.T) {
	ctx := testenv.Browser(t)
	h, err := testPage()
	if err != nil {
		t.Fatal(err)
	}
	base := testenv.Serve(t, h)
	logs := watchConsole(ctx)

	if err := chromedp.Do(ctx, chromedp.Navigate(base+"/test/")); err != nil {
		t.Fatal(err)
	}
	_, err = chromedp.Run(ctx, chromedp.Poll[bool]("window.__horizonTests?.done === true",
		chromedp.WithPollingInterval(50*time.Millisecond), chromedp.WithPollingTimeout(60*time.Second)))
	if err != nil {
		logs.failOnErrors(t)
		t.Fatalf("tests did not finish: %v", err)
	}
	results, err := chromedp.Run(ctx, chromedp.Evaluate[[]jsResult]("window.__horizonTests.results"))
	if err != nil {
		t.Fatal(err)
	}
	if len(results) == 0 {
		t.Fatal("no JS tests ran")
	}
	for _, r := range results {
		t.Run(r.Name, func(t *testing.T) {
			if !r.OK {
				t.Error(r.Error)
			}
		})
	}
	logs.failOnErrors(t)
}


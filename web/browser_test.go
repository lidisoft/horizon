// page drives one browser tab.
type page struct {
	t    *testing.T
	ctx  context.Context
	logs *console
}

func newPage(t *testing.T) *page {
	ctx := testenv.Browser(t)
	return &page{t: t, ctx: ctx, logs: watchConsole(ctx)}
}

// poll waits until expr is truthy and returns it as a string. An exception
// (the view not mounted yet) counts as not yet.
func (p *page) poll(expr string) string {
	p.t.Helper()
	safe := `(() => { try { return (` + expr + `); } catch { return false; } })()`
	v, err := chromedp.Run(p.ctx, chromedp.Poll[string](safe, chromedp.WithPollingInterval(50*time.Millisecond), chromedp.WithPollingTimeout(10*time.Second)))
	if err != nil {
		p.logs.failOnErrors(p.t)
		state, _ := chromedp.Run(p.ctx, chromedp.Evaluate[string](`location.href + " | " + (document.querySelector("hzn-app")?.shadowRoot?.getElementById("outlet")?.firstElementChild?.shadowRoot?.textContent ?? "").replace(/\s+/g, " ").slice(0, 300)`))
		p.t.Fatalf("waiting for %s: %v\npage: %s", expr, err, state)
	}
	return v
}

// pollAcross is poll for a page that navigates to other origins meanwhile
// (an identity provider): evaluation errors during navigation count as
// not yet.
func (p *page) pollAcross(expr string) {
	p.t.Helper()
	safe := `(() => { try { return !!(` + expr + `); } catch { return false; } })()`
	for deadline := time.Now().Add(10 * time.Second); ; time.Sleep(50 * time.Millisecond) {
		if ok, err := chromedp.Run(p.ctx, chromedp.Evaluate[bool](safe)); err == nil && ok {
			return
		}
		if time.Now().After(deadline) {
			href, _ := chromedp.Run(p.ctx, chromedp.Evaluate[string](`location.href`))
			p.t.Fatalf("waiting for %s (at %s)", expr, href)
		}
	}
}

func (p *page) do(actions ...chromedp.Action[chromedp.Void]) {
	p.t.Helper()
	if err := chromedp.Do(p.ctx, actions...); err != nil {
		p.t.Fatal(err)
	}
}

func (p *page) eval(expr string) {
	p.t.Helper()
	p.do(chromedp.Evaluate[chromedp.Void](expr))
}

// click clicks the middle of an element with the mouse, as a user would.
func (p *page) click(selector string) {
	p.t.Helper()
	// Where the target is once it holds still between two polls (50 ms
	// apart), the same element in the same place: a view still rendering
	// can move it from under the pointer, or replace it between the press
	// and the release, and the click is lost.
	p.eval(`window.__hznClickAt = ""; window.__hznClickEl = null`)
	box := p.poll(`(() => {
		const el = ` + selector + `;
		el.scrollIntoView({ block: "center" });
		const b = el.getBoundingClientRect();
		const at = JSON.stringify([b.x + b.width / 2, b.y + b.height / 2]);
		const still = window.__hznClickAt === at && window.__hznClickEl === el;
		window.__hznClickAt = at;
		window.__hznClickEl = el;
		return still && at;
	})()`)
	var xy [2]float64
	if err := json.Unmarshal([]byte(box), &xy); err != nil {
		p.t.Fatalf("click %s: %v", selector, err)
	}
	p.do(chromedp.MouseClickXY(xy[0], xy[1]))
}

// typeInto focuses a control and types text, as a user would.
func (p *page) typeInto(selector, text string) {
	p.t.Helper()
	p.poll(selector + ` && "found"`)
	p.eval(selector + `.focus()`)
	p.do(chromedp.KeyEvent(text))
}

// press presses a shortcut key. chromedp types a key as keydown, char and
// keyup, and the char isn't cancelled with the keydown: a shortcut opening a
// field quickly enough would get its own letter typed into it, which a
// browser never does. So only keydown and keyup.
func (p *page) press(key rune) {
	p.t.Helper()
	p.do(chromedp.Func(func(ctx context.Context, t *chromedp.Target) error {
		for _, e := range kb.Encode(key) {
			if e.Type == kb.KeyChar {
				continue
			}
			if _, err := cdp.Call(ctx, t, input.DispatchKeyEvent, *e); err != nil {
				return err
			}
		}
		return nil
	}))
}


var serveAddr = flag.String("serve", "", "serve the test page on this address (e.g. :8089) for a local browser, instead of running the tests")

func TestMain(m *testing.M) {
	flag.Parse()
	if *serveAddr != "" {
		os.Exit(serveForHumans(*serveAddr))
	}
	os.Exit(testenv.Main(m, testenv.Chrome))
}

// testFS holds web/test: the runner and the *.test.js files. It is read from
// disk, so it never ships in the binary.
var testFS = os.DirFS("test")

// testPage serves the runner page, the test modules and the real app assets.
func testPage() (http.Handler, error) {
	w, err := server.NewWeb(web.FS())
	if err != nil {
		return nil, err
	}
	app := server.NewEngine(server.Deps{Log: zerolog.Nop(), Web: w})

	imports := w.Imports()
	var testFiles []string
	err = fs.WalkDir(testFS, ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(p, ".js") {
			return err
		}
		imports["horizon-test/"+p] = "/test/" + p
		if strings.HasSuffix(p, ".test.js") {
			testFiles = append(testFiles, p)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	sort.Strings(testFiles)

	var entry strings.Builder
	entry.WriteString("// Generated by web/browser_test.go: every *.test.js, then run().\n")
	for _, f := range testFiles {
		fmt.Fprintf(&entry, "import %q;\n", "horizon-test/"+f)
	}
	entry.WriteString(`import { run } from "horizon-test/runner.js";` + "\nrun();\n")

	importMap, err := json.Marshal(map[string]any{"imports": imports})
	if err != nil {
		return nil, err
	}
	tpl, err := template.ParseFS(testFS, "index.html")
	if err != nil {
		return nil, err
	}
	var page bytes.Buffer
	err = tpl.Execute(&page, map[string]any{"ImportMap": template.HTML(importMap), "LDS": w.LDSBase()})
	if err != nil {
		return nil, err
	}

	files := http.StripPrefix("/test/", http.FileServer(http.FS(testFS)))
	mux := http.NewServeMux()
	mux.HandleFunc("GET /test/{$}", func(rw http.ResponseWriter, _ *http.Request) {
		rw.Header().Set("Content-Security-Policy", server.CSP(importMap))
		rw.Header().Set("Content-Type", "text/html; charset=utf-8")
		_, _ = rw.Write(page.Bytes())
	})
	mux.HandleFunc("GET /test/entry.js", func(rw http.ResponseWriter, _ *http.Request) {
		rw.Header().Set("Content-Type", "text/javascript; charset=utf-8")
		_, _ = rw.Write([]byte(entry.String()))
	})
	mux.Handle("GET /test/", http.HandlerFunc(func(rw http.ResponseWriter, r *http.Request) {
		rw.Header().Set("Cache-Control", "no-store")
		files.ServeHTTP(rw, r)
	}))
	mux.Handle("/", app)
	return mux, nil
}

// console collects the page's console and browser log messages.
type console struct {
	mu       sync.Mutex
	messages []chromedp.ConsoleMessage
}

func watchConsole(ctx context.Context) *console {
	c := &console{}
	messages := chromedp.Console(ctx)
	go func() {
		for m, err := range messages {
			if err != nil {
				return
			}
			c.mu.Lock()
			c.messages = append(c.messages, m)
			c.mu.Unlock()
		}
	}()
	return c
}

// knownIssues are browser messages accepted until an upstream fix lands.
var knownIssues = []struct{ text, why string }{
	{
		// LDS v0.0.5 icons.svg has style="display:none" on its root, set
		// through innerHTML; the runtime hides the sprite through the CSSOM
		// anyway. Reported to the design system; remove when fixed.
		text: "Applying inline style violates the following Content Security Policy",
		why:  "LDS icon sprite (v0.0.5)",
	},
}

// failOnErrors fails the test for uncaught exceptions, console errors and
// CSP violations.
func (c *console) failOnErrors(t *testing.T) {
	t.Helper()
	c.mu.Lock()
	defer c.mu.Unlock()
next:
	for _, m := range c.messages {
		if !m.IsException() && m.Type != "error" && m.Type != "assert" {
			continue
		}
		for _, k := range knownIssues {
			if strings.Contains(m.Text, k.text) {
				t.Logf("known issue (%s): %s", k.why, m.Text)
				continue next
			}
		}
		t.Errorf("browser %s", m)
	}
}

type jsResult struct {
	Name  string `json:"name"`
	OK    bool   `json:"ok"`
	Ms    int    `json:"ms"`
	Error string `json:"error"`
}

// TestWebUnits runs web/test/**/*.test.js in Chrome; each JS test is a subtest.
func TestWebUnits(t *testing.T) {
	ctx := testenv.Browser(t)
	h, err := testPage()
	if err != nil {
		t.Fatal(err)
	}
	base := testenv.Serve(t, h)
	logs := watchConsole(ctx)

	if err := chromedp.Do(ctx, chromedp.Navigate(base+"/test/")); err != nil {
		t.Fatal(err)
	}
	_, err = chromedp.Run(ctx, chromedp.Poll[bool]("window.__horizonTests?.done === true",
		chromedp.WithPollingInterval(50*time.Millisecond), chromedp.WithPollingTimeout(60*time.Second)))
	if err != nil {
		logs.failOnErrors(t)
		t.Fatalf("tests did not finish: %v", err)
	}
	results, err := chromedp.Run(ctx, chromedp.Evaluate[[]jsResult]("window.__horizonTests.results"))
	if err != nil {
		t.Fatal(err)
	}
	if len(results) == 0 {
		t.Fatal("no JS tests ran")
	}
	for _, r := range results {
		t.Run(r.Name, func(t *testing.T) {
			if !r.OK {
				t.Error(r.Error)
			}
		})
	}
	logs.failOnErrors(t)
}

// TestAppShell loads the real page and drives it with the keyboard.
func TestAppShell(t *testing.T) {
	ctx := testenv.Browser(t)
	w, err := server.NewWeb(web.FS())
	if err != nil {
		t.Fatal(err)
	}
	ok := func(context.Context) error { return nil }
	checks := []server.Check{{Name: "postgres", Check: ok}, {Name: "nats", Check: ok}, {Name: "s3", Check: ok}, {Name: "schema", Check: ok}}
	base := testenv.Serve(t, server.NewEngine(server.Deps{Log: zerolog.Nop(), Web: w, Checks: checks}))
	logs := watchConsole(ctx)

	const app = `document.querySelector("hzn-app").shadowRoot`
	poll := func(expr string) string {
		t.Helper()
		v, err := chromedp.Run(ctx, chromedp.Poll[string](expr, chromedp.WithPollingInterval(50*time.Millisecond), chromedp.WithPollingTimeout(10*time.Second)))
		if err != nil {
			logs.failOnErrors(t)
			t.Fatalf("waiting for %s: %v", expr, err)
		}
		return v
	}
	text := func(s string) string { return strings.Join(strings.Fields(s), " ") }

	if err := chromedp.Do(ctx, chromedp.Navigate(base+"/")); err != nil {
		t.Fatal(err)
	}

	// items lists the text of each dt and dd in a <dl>, in order.
	items := func(dl string) string {
		return text(poll(`[...(` + dl + `)?.children ?? []].map((e) => e.textContent.trim()).join(" | ")`))
	}

	// The home view renders inside the frame and shows the readiness checks.
	got := items(app + `.querySelector("hzn-home")?.shadowRoot?.querySelector("dl.checks")`)
	if got != "PostgreSQL | OK | NATS | OK | Object storage | OK | Database schema | OK" {
		t.Errorf("checks = %q", got)
	}
	poll(app + `.querySelector('lds-nav-item[data-route="home"][active]') && "active"`)

	// "?" opens the shortcut help, generated from the registry.
	if err := chromedp.Do(ctx, chromedp.KeyEvent("?")); err != nil {
		t.Fatal(err)
	}
	poll(app + `.getElementById("help").hasAttribute("open") && "open"`)
	help := items(app + `.querySelector(".help")`)
	for _, want := range []string{"Open the command palette | Ctrl+K", "Show keyboard shortcuts | ?", "Go to home | G then H"} {
		if !strings.Contains(help, want) {
			t.Errorf("help %q lacks %q", help, want)
		}
	}
	if err := chromedp.Do(ctx, chromedp.Evaluate[chromedp.Void](app+`.getElementById("help").removeAttribute("open")`)); err != nil {
		t.Fatal(err)
	}

	// Ctrl+K opens the palette (the container runs Linux, so mod is Ctrl).
	if err := chromedp.Do(ctx, chromedp.KeyEvent("k", chromedp.KeyModifiers(chromedp.ModifierCtrl))); err != nil {
		t.Fatal(err)
	}
	poll(app + `.getElementById("palette").hasAttribute("open") && "open"`)
	if err := chromedp.Do(ctx, chromedp.Evaluate[chromedp.Void](app+`.getElementById("palette").removeAttribute("open")`)); err != nil {
		t.Fatal(err)
	}

	// Unknown paths render the not-found view; "g h" goes home without a reload.
	if err := chromedp.Do(ctx, chromedp.Navigate(base+"/nowhere")); err != nil {
		t.Fatal(err)
	}
	poll(app + `.querySelector("hzn-not-found")?.shadowRoot?.textContent.includes("/nowhere") && "shown"`)
	if _, err := chromedp.Run(ctx, chromedp.Evaluate[bool](`window.__marker = true`)); err != nil {
		t.Fatal(err)
	}
	if err := chromedp.Do(ctx, chromedp.KeyEvent("g"), chromedp.KeyEvent("h")); err != nil {
		t.Fatal(err)
	}
	poll(`location.pathname === "/" && window.__marker === true && ` + app + `.querySelector("hzn-home") && "home"`)

	logs.failOnErrors(t)
}

// serveForHumans serves the test page for a local browser:
//
//	go test ./web -run TestWebUnits -args -serve :8089
func serveForHumans(addr string) int {
	h, err := testPage()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt)
	defer stop()
	fmt.Printf("web tests: http://localhost%s/test/ (Ctrl+C to stop)\n", addr)
	if err := server.Run(ctx, addr, h, zerolog.Nop()); err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	return 0
}
